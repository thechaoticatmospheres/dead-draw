export function sampleKey(name, { weapon = "courtesy", kind = "walker" } = {}) {
  if (name === "shot") return `shot:${weapon}`;
  if (name === "enemy") return `enemy:${kind}`;
  if (["reload", "reloadEnd", "switch", "empty"].includes(name)) {
    const family = WEAPON_HANDLING[weapon];
    return family ? `${name}:${family}` : null;
  }
  return null;
}

export function sampleUrl(sample, base = import.meta.env?.BASE_URL || "/") {
  return `${base.replace(/\/?$/, "/")}assets/audio/${sample.file}`;
}
